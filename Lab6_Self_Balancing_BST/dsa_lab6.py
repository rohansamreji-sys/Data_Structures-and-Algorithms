def run_tree_experiment(tree_type, insertion_order,
                        search_ids, deletion_ids):

    tree = tree_type()

    # Create patient records.
    records = [
        (patient_id, f"Patient {patient_id}")
        for patient_id in insertion_order
    ]

    # -----------------------------------------
    # 1. INSERTION TIME
    # -----------------------------------------

    start_time = time.perf_counter()

    for patient_id, patient_name in records:
        tree.insert(patient_id, patient_name)

    insertion_time = time.perf_counter() - start_time

    # Record height after insertion.
    height_after_insert = tree.height()

    # Record rotations for AVL.
    rotations = getattr(tree, "rotations", 0)

    # -----------------------------------------
    # 2. SUCCESSFUL SEARCH COMPARISONS
    # -----------------------------------------

    total_comparisons = 0

    for patient_id in search_ids:

        tree.reset_comparisons()

        result = tree.search(patient_id)

        expected_result = f"Patient {patient_id}"

        if result != expected_result:
            raise AssertionError(
                f"Search failed in {tree_type.__name__} "
                f"for Patient ID {patient_id}. "
                f"Expected: {expected_result}, "
                f"Received: {result}"
            )

        total_comparisons += tree.comparisons

    average_comparisons = (
        total_comparisons / len(search_ids)
        if len(search_ids) > 0
        else 0
    )

    # -----------------------------------------
    # 3. DELETE 20% OF THE RECORDS
    # -----------------------------------------

    for patient_id in deletion_ids:

        deleted = tree.delete(patient_id)

        if deleted is not True:
            raise AssertionError(
                f"Deletion failed in {tree_type.__name__} "
                f"for Patient ID {patient_id}"
            )

    height_after_deletion = tree.height()

    # -----------------------------------------
    # 4. VALIDATE THE REMAINING TREE
    # -----------------------------------------

    if isinstance(tree, AVLTree):

        assert tree.is_balanced(), (
            "AVL balance validation failed."
        )

        assert tree.is_bst(), (
            "AVL BST property validation failed."
        )

    # Return all measured results.
    return {
        "height_after_insert": height_after_insert,
        "insertion_seconds": insertion_time,
        "rotations": rotations,
        "avg_search_comparisons": average_comparisons,
        "height_after_delete": height_after_deletion
    }


