class TreapNode:
    def __init__(self, key, name, priority):
        self.key = key
        self.name = name
        self.priority = priority
        self.left = None
        self.right = None


class Treap:
    def __init__(self, seed=42):
        self.root = None
        self.rng = random.Random(seed)

    def rotate_right(self, y):
        x = y.left
        y.left = x.right
        x.right = y
        return x

    def rotate_left(self, x):
        y = x.right
        x.right = y.left
        y.left = x
        return y

    def insert(self, key, name):
        priority = self.rng.random()
        self.root = self._insert(
            self.root, key, name, priority
        )

    def _insert(self, node, key, name, priority):
        if node is None:
            return TreapNode(key, name, priority)

        if key < node.key:
            node.left = self._insert(
                node.left, key, name, priority
            )

            if node.left.priority < node.priority:
                node = self.rotate_right(node)

        elif key > node.key:
            node.right = self._insert(
                node.right, key, name, priority
            )

            if node.right.priority < node.priority:
                node = self.rotate_left(node)

        else:
            node.name = name

        return node

    def search(self, key):
        current = self.root

        while current is not None:
            if key == current.key:
                return current.name
            elif key < current.key:
                current = current.left
            else:
                current = current.right

        return None

    def merge(self, left, right):
        if left is None:
            return right

        if right is None:
            return left

        if left.priority < right.priority:
            left.right = self.merge(left.right, right)
            return left

        right.left = self.merge(left, right.left)
        return right

    def delete(self, key):
        self.root, deleted = self._delete(self.root, key)
        return deleted

    def _delete(self, node, key):
        if node is None:
            return None, False

        if key < node.key:
            node.left, deleted = self._delete(node.left, key)
            return node, deleted

        if key > node.key:
            node.right, deleted = self._delete(node.right, key)
            return node, deleted

        # Replace the deleted node with a merged subtree
        return self.merge(node.left, node.right), True

    def inorder(self):
        result = []
        stack = []
        current = self.root

        while stack or current is not None:
            while current is not None:
                stack.append(current)
                current = current.left

            current = stack.pop()
            result.append((current.key, current.name))
            current = current.right

        return result

    def height(self):
        def calculate(node):
            if node is None:
                return 0

            return 1 + max(
                calculate(node.left),
                calculate(node.right)
            )

        return calculate(self.root)

    def is_valid(self):
        def check(node, lower, upper):
            if node is None:
                return True

            if lower is not None and node.key <= lower:
                return False

            if upper is not None and node.key >= upper:
                return False

            if node.left is not None:
                if node.left.priority < node.priority:
                    return False

            if node.right is not None:
                if node.right.priority < node.priority:
                    return False

            return (
                check(node.left, lower, node.key)
                and check(node.right, node.key, upper)
            )

        return check(self.root, None, None)


