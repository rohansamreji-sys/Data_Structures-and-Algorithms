def generate_workloads(n, seed):
    rng = random.Random(seed)

    # Dataset 1: Sequential IDs
    sequential = list(range(1, n + 1))

    # Dataset 2: Random permutation
    random_data = sequential.copy()
    rng.shuffle(random_data)

    # Dataset 3: Nearly sorted
    nearly_sorted = sequential.copy()

    # Select approximately 5% of positions
    # and swap them in pairs.
    number_of_positions = max(2, round(0.05 * n))
    selected_positions = rng.sample(
        range(n), number_of_positions
    )

    for i in range(0, len(selected_positions) - 1, 2):
        first = selected_positions[i]
        second = selected_positions[i + 1]

        nearly_sorted[first], nearly_sorted[second] = (
            nearly_sorted[second],
            nearly_sorted[first]
        )

    return {
        "Sequential": sequential,
        "Random": random_data,
        "Nearly Sorted": nearly_sorted
    }


