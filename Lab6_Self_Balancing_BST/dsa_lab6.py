#RED-BLACK TREE IMPLEMENTATION

class RBNode:
    def __init__(self, key, name):
        self.key = key
        self.name = name
        self.color = "RED"
        self.left = None
        self.right = None
        self.parent = None


class RedBlackTree:
    def __init__(self):
        self.root = None

    def rotate_left(self, x):
        y = x.right
        x.right = y.left

        if y.left is not None:
            y.left.parent = x

        y.parent = x.parent

        if x.parent is None:
            self.root = y
        elif x == x.parent.left:
            x.parent.left = y
        else:
            x.parent.right = y

        y.left = x
        x.parent = y

    def rotate_right(self, y):
        x = y.left
        y.left = x.right

        if x.right is not None:
            x.right.parent = y

        x.parent = y.parent

        if y.parent is None:
            self.root = x
        elif y == y.parent.right:
            y.parent.right = x
        else:
            y.parent.left = x

        x.right = y
        y.parent = x

    def insert(self, key, name):
        new_node = RBNode(key, name)
        parent = None
        current = self.root

        # Ordinary BST insertion
        while current is not None:
            parent = current

            if key < current.key:
                current = current.left
            elif key > current.key:
                current = current.right
            else:
                current.name = name
                return

        new_node.parent = parent

        if parent is None:
            self.root = new_node
        elif key < parent.key:
            parent.left = new_node
        else:
            parent.right = new_node

        self.fix_insert(new_node)

    def fix_insert(self, node):
        while (
            node != self.root
            and node.parent.color == "RED"
        ):
            parent = node.parent
            grandparent = parent.parent

            if parent == grandparent.left:
                uncle = grandparent.right

                # Case 1: Red uncle - recolour
                if uncle is not None and uncle.color == "RED":
                    parent.color = "BLACK"
                    uncle.color = "BLACK"
                    grandparent.color = "RED"
                    node = grandparent

                else:
                    # Case 2: Inner child - rotate parent
                    if node == parent.right:
                        node = parent
                        self.rotate_left(node)
                        parent = node.parent
                        grandparent = parent.parent

                    # Case 3: Outer child - rotate grandparent
                    parent.color = "BLACK"
                    grandparent.color = "RED"
                    self.rotate_right(grandparent)

            else:
                uncle = grandparent.left

                # Mirror Case 1
                if uncle is not None and uncle.color == "RED":
                    parent.color = "BLACK"
                    uncle.color = "BLACK"
                    grandparent.color = "RED"
                    node = grandparent

                else:
                    # Mirror Case 2
                    if node == parent.left:
                        node = parent
                        self.rotate_right(node)
                        parent = node.parent
                        grandparent = parent.parent

                    # Mirror Case 3
                    parent.color = "BLACK"
                    grandparent.color = "RED"
                    self.rotate_left(grandparent)

        self.root.color = "BLACK"

    def search(self, key):
        current = self.root

        while current is not None:
            if key == current.key:
                return current.name
            elif key < current.key:
                current = current.left
            else:
                current = current.right

        return None

    def inorder(self):
        result = []
        stack = []
        current = self.root

        while stack or current is not None:
            while current is not None:
                stack.append(current)
                current = current.left

            current = stack.pop()
            result.append((current.key, current.name))
            current = current.right

        return result

    def height(self):
        def calculate(node):
            if node is None:
                return 0

            return 1 + max(
                calculate(node.left),
                calculate(node.right)
            )

        return calculate(self.root)

    # Check BST ordering and Red-Black properties
    def is_valid(self):
        if self.root is None:
            return True

        if self.root.color != "BLACK":
            return False

        def check(node, lower, upper):
            if node is None:
                return True, 1

            if lower is not None and node.key <= lower:
                return False, 0

            if upper is not None and node.key >= upper:
                return False, 0

            if node.color == "RED":
                if node.left is not None and node.left.color == "RED":
                    return False, 0
                if node.right is not None and node.right.color == "RED":
                    return False, 0

            left_valid, left_black_height = check(
                node.left, lower, node.key
            )

            right_valid, right_black_height = check(
                node.right, node.key, upper
            )

            if not left_valid or not right_valid:
                return False, 0

            if left_black_height != right_black_height:
                return False, 0

            black_count = (
                left_black_height
                + (1 if node.color == "BLACK" else 0)
            )

            return True, black_count

        valid, _ = check(self.root, None, None)
        return valid


