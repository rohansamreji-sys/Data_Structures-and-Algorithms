class AVLNode:
    def __init__(self, patient_id, patient_name):
        self.patient_id = patient_id
        self.patient_name = patient_name
        self.left = None
        self.right = None
        self.height = 1


class AVLTree:
    def __init__(self):
        self.root = None
        self.comparisons = 0
        self.rotations = 0

    def reset_comparisons(self):
        self.comparisons = 0

    def reset_rotations(self):
        self.rotations = 0

    def node_height(self, node):
        if node is None:
            return 0
        return node.height

    def balance_factor(self, node):
        if node is None:
            return 0
        return self.node_height(node.left) - self.node_height(node.right)

    def update_height(self, node):
        node.height = 1 + max(
            self.node_height(node.left),
            self.node_height(node.right)
        )

    # Right rotation (used for LL and part of RL/LR cases)
    def rotate_right(self, y):
        x = y.left
        subtree = x.right

        x.right = y
        y.left = subtree

        self.update_height(y)
        self.update_height(x)

        self.rotations += 1
        return x

    # Left rotation (used for RR and part of LR/RL cases)
    def rotate_left(self, x):
        y = x.right
        subtree = y.left

        y.left = x
        x.right = subtree

        self.update_height(x)
        self.update_height(y)

        self.rotations += 1
        return y

    # Restore AVL balance after insertion or deletion
    def rebalance(self, node):
        if node is None:
            return None

        self.update_height(node)
        balance = self.balance_factor(node)

        # Left-heavy subtree
        if balance > 1:
            if self.balance_factor(node.left) < 0:
                # LR case
                node.left = self.rotate_left(node.left)

            # LL case
            return self.rotate_right(node)

        # Right-heavy subtree
        if balance < -1:
            if self.balance_factor(node.right) > 0:
                # RL case
                node.right = self.rotate_right(node.right)

            # RR case
            return self.rotate_left(node)

        return node

    # Insert a patient record
    def insert(self, patient_id, patient_name):
        self.root = self._insert(
            self.root, patient_id, patient_name
        )

    def _insert(self, node, patient_id, patient_name):
        if node is None:
            return AVLNode(patient_id, patient_name)

        self.comparisons += 1

        if patient_id < node.patient_id:
            node.left = self._insert(
                node.left, patient_id, patient_name
            )
        elif patient_id > node.patient_id:
            node.right = self._insert(
                node.right, patient_id, patient_name
            )
        else:
            node.patient_name = patient_name
            return node

        return self.rebalance(node)

    # Search for a patient record
    def search(self, patient_id):
        current = self.root

        while current is not None:
            self.comparisons += 1

            if patient_id == current.patient_id:
                return current.patient_name

            self.comparisons += 1

            if patient_id < current.patient_id:
                current = current.left
            else:
                current = current.right

        return None

    # Find the smallest node in a subtree
    def minimum_node(self, node):
        current = node

        while current.left is not None:
            current = current.left

        return current

    # Delete a patient record
    def delete(self, patient_id):
        self.root, deleted = self._delete(
            self.root, patient_id
        )
        return deleted

    def _delete(self, node, patient_id):
        if node is None:
            return None, False

        deleted = False

        if patient_id < node.patient_id:
            node.left, deleted = self._delete(
                node.left, patient_id
            )

        elif patient_id > node.patient_id:
            node.right, deleted = self._delete(
                node.right, patient_id
            )

        else:
            deleted = True

            # Case 1: No child or only right child
            if node.left is None:
                return node.right, True

            # Case 2: Only left child
            if node.right is None:
                return node.left, True

            # Case 3: Two children
            successor = self.minimum_node(node.right)

            node.patient_id = successor.patient_id
            node.patient_name = successor.patient_name

            node.right, _ = self._delete(
                node.right, successor.patient_id
            )

        # Rebalance only if a deletion actually occurred
        if not deleted:
            return node, False

        return self.rebalance(node), True

    # In-order traversal
    def inorder(self):
        result = []
        stack = []
        current = self.root

        while stack or current is not None:
            while current is not None:
                stack.append(current)
                current = current.left

            current = stack.pop()
            result.append(
                (current.patient_id, current.patient_name)
            )
            current = current.right

        return result

    # Height of the complete tree
    def height(self):
        return self.node_height(self.root)

    # Verify every node's balance factor and stored height
    def is_balanced(self):
        def check(node):
            if node is None:
                return True, 0

            left_valid, left_height = check(node.left)
            right_valid, right_height = check(node.right)

            actual_height = 1 + max(
                left_height, right_height
            )

            valid_balance = abs(
                left_height - right_height
            ) <= 1

            valid_height = node.height == actual_height

            return (
                left_valid and right_valid
                and valid_balance and valid_height,
                actual_height
            )

        valid, _ = check(self.root)
        return valid

    # Verify the Binary Search Tree ordering property
    def is_bst(self):
        def check(node, lower, upper):
            if node is None:
                return True

            if lower is not None and node.patient_id <= lower:
                return False

            if upper is not None and node.patient_id >= upper:
                return False

            return (
                check(node.left, lower, node.patient_id)
                and check(node.right, node.patient_id, upper)
            )

        return check(self.root, None, None)

    # Display the tree sideways
    def display(self):
        def show(node, level=0):
            if node is not None:
                show(node.right, level + 1)
                print(
                    "    " * level
                    + f"{node.patient_id} ({node.height})"
                )
                show(node.left, level + 1)

        if self.root is None:
            print("Tree is empty.")
        else:
            show(self.root)

