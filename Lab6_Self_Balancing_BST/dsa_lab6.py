class PlainBST:
    def __init__(self):
        self.root = None
        self.comparisons = 0

    def reset_comparisons(self):
        self.comparisons = 0

    # Insert a patient record
    def insert(self, patient_id, patient_name):
        new_node = BSTNode(patient_id, patient_name)

        if self.root is None:
            self.root = new_node
            return

        current = self.root

        while True:
            self.comparisons += 1

            if patient_id == current.patient_id:
                current.patient_name = patient_name
                return

            if patient_id < current.patient_id:
                if current.left is None:
                    current.left = new_node
                    return
                current = current.left
            else:
                if current.right is None:
                    current.right = new_node
                    return
                current = current.right

    # Search and return the patient name
    def search(self, patient_id):
        current = self.root

        while current is not None:
            self.comparisons += 1

            if patient_id == current.patient_id:
                return current.patient_name

            self.comparisons += 1

            if patient_id < current.patient_id:
                current = current.left
            else:
                current = current.right

        return None

    # Find the smallest node in a subtree
    def minimum_node(self, node):
        current = node

        while current.left is not None:
            current = current.left

        return current

    # Delete a patient record
    def delete(self, patient_id):
        parent = None
        current = self.root

        while current is not None and current.patient_id != patient_id:
            parent = current

            if patient_id < current.patient_id:
                current = current.left
            else:
                current = current.right

        if current is None:
            return False

        # Case 1: Node has two children
        if current.left is not None and current.right is not None:
            successor_parent = current
            successor = current.right

            while successor.left is not None:
                successor_parent = successor
                successor = successor.left

            current.patient_id = successor.patient_id
            current.patient_name = successor.patient_name

            parent = successor_parent
            current = successor

        # Case 2: Node has zero or one child
        if current.left is not None:
            child = current.left
        else:
            child = current.right

        if parent is None:
            self.root = child
        elif parent.left == current:
            parent.left = child
        else:
            parent.right = child

        return True

    # In-order traversal
    def inorder(self):
        result = []
        stack = []
        current = self.root

        while stack or current is not None:
            while current is not None:
                stack.append(current)
                current = current.left

            current = stack.pop()
            result.append(
                (current.patient_id, current.patient_name)
            )
            current = current.right

        return result

    # Calculate tree height
    def height(self):
        if self.root is None:
            return 0

        stack = [(self.root, 1)]
        maximum_height = 0

        while stack:
            node, level = stack.pop()
            maximum_height = max(maximum_height, level)

            if node.left is not None:
                stack.append((node.left, level + 1))

            if node.right is not None:
                stack.append((node.right, level + 1))

        return maximum_height

    # Display tree sideways
    def display(self):
        def show(node, level=0):
            if node is not None:
                show(node.right, level + 1)
                print("    " * level + str(node.patient_id))
                show(node.left, level + 1)

        if self.root is None:
            print("Tree is empty.")
        else:
            show(self.root)

