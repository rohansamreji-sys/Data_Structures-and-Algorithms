class SplayNode:
    def __init__(self, key, name):
        self.key = key
        self.name = name
        self.left = None
        self.right = None


class SplayTree:
    def __init__(self):
        self.root = None

    def rotate_right(self, x):
        y = x.left
        x.left = y.right
        y.right = x
        return y

    def rotate_left(self, x):
        y = x.right
        x.right = y.left
        y.left = x
        return y

    def splay(self, root, key):
        if root is None or root.key == key:
            return root

        # Key lies in the left subtree
        if key < root.key:
            if root.left is None:
                return root

            # Zig-Zig
            if key < root.left.key:
                root.left.left = self.splay(
                    root.left.left, key
                )
                root = self.rotate_right(root)

            # Zig-Zag
            elif key > root.left.key:
                root.left.right = self.splay(
                    root.left.right, key
                )

                if root.left.right is not None:
                    root.left = self.rotate_left(root.left)

            if root.left is None:
                return root

            return self.rotate_right(root)

        # Key lies in the right subtree
        else:
            if root.right is None:
                return root

            # Zig-Zag
            if key < root.right.key:
                root.right.left = self.splay(
                    root.right.left, key
                )

                if root.right.left is not None:
                    root.right = self.rotate_right(root.right)

            # Zig-Zig
            elif key > root.right.key:
                root.right.right = self.splay(
                    root.right.right, key
                )
                root = self.rotate_left(root)

            if root.right is None:
                return root

            return self.rotate_left(root)

    def insert(self, key, name):
        if self.root is None:
            self.root = SplayNode(key, name)
            return

        self.root = self.splay(self.root, key)

        if self.root.key == key:
            self.root.name = name
            return

        new_node = SplayNode(key, name)

        if key < self.root.key:
            new_node.right = self.root
            new_node.left = self.root.left
            self.root.left = None
        else:
            new_node.left = self.root
            new_node.right = self.root.right
            self.root.right = None

        self.root = new_node

    def search(self, key):
        self.root = self.splay(self.root, key)

        if self.root is not None and self.root.key == key:
            return self.root.name

        return None

    def delete(self, key):
        if self.root is None:
            return False

        self.root = self.splay(self.root, key)

        if self.root.key != key:
            return False

        old_root = self.root

        if old_root.left is None:
            self.root = old_root.right
        else:
            left_subtree = old_root.left
            left_subtree = self.splay(left_subtree, key)
            left_subtree.right = old_root.right
            self.root = left_subtree

        return True

    def inorder(self):
        result = []
        stack = []
        current = self.root

        while stack or current is not None:
            while current is not None:
                stack.append(current)
                current = current.left

            current = stack.pop()
            result.append((current.key, current.name))
            current = current.right

        return result

